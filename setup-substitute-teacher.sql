-- teacher_locked_terms: kasama na ang lock ng MAY-ARI sa mga subject na
-- hiniram ng caller — para read-only agad ang na-submit nang term sa kanya.
create or replace function public.teacher_locked_terms()
returns table(subject_code text, sy text, period text, submitted_at timestamptz)
language sql stable security definer set search_path to 'public'
as $$
  select r.subject_code, r.sy, r.period, r.submitted_at
  from sas_grade_reviews r
  where r.status = 'submitted'
    and ( r.teacher_id = public.current_teacher_id()
       or exists (
            select 1 from reg_class_subjects cs
            where cs.subject_code = r.subject_code
              and cs.term_teachers is not null
              and (case when (cs.term_teachers ->> r.period) ~ '^\d+$'
                        then (cs.term_teachers ->> r.period)::bigint end) = r.teacher_id
              and exists (select 1 from jsonb_each_text(cs.term_teachers) e
                          where (case when e.value ~ '^\d+$' then e.value::bigint end)
                                = public.current_teacher_id()) )
       -- Hiram na sheet: ang lock ng may-ari ay lock din sa substitute.
       or ( r.teacher_id = any (public.sub_owners_of_subject(r.subject_code))
            -- Huwag i-lock kung may SARILING load ang caller sa subject na
            -- ito — iba ang sheet na iyon at hindi ito nakatali sa may-ari.
            and not exists (
              select 1 from reg_class_subjects cs2
              where cs2.subject_code = r.subject_code
                and (cs2.teacher_id = public.current_teacher_id()
                     or (cs2.term_teachers is not null and exists (
                           select 1 from jsonb_each_text(cs2.term_teachers) e2
                           where (case when e2.value ~ '^\d+$' then e2.value::bigint end)
                                 = public.current_teacher_id())))) ) );
$$;
grant execute on function public.teacher_locked_terms() to authenticated;

-- teacher_my_revisions / ack / mark-resolved: gumagana na rin sa hiram na sheet,
-- para matapos ng substitute ang ibinalik na term ng naka-leave na teacher.
create or replace function public.teacher_my_revisions()
returns table(subject_code text, subject_name text, sy text, period text,
              note text, returned_at timestamptz, needs_popup boolean)
language sql stable security definer set search_path to 'public'
as $$
  select r.subject_code, coalesce(s.full_name, r.subject_code), r.sy, r.period,
         r.note, r.returned_at, (not r.popup_seen) as needs_popup
  from sas_grade_reviews r
  left join reg_subjects s on s.code = r.subject_code
  where r.status = 'needs_revision'
    and ( r.teacher_id = public.current_teacher_id()
       or r.teacher_id = any (public.sub_owners_of_subject(r.subject_code)) )
  order by r.returned_at desc;
$$;
grant execute on function public.teacher_my_revisions() to authenticated;

create or replace function public.teacher_ack_revision_popup(
  p_subject_code text, p_sy text, p_period text)
returns void language plpgsql security definer set search_path to 'public'
as $$
begin
  update sas_grade_reviews
     set popup_seen = true, updated_at = now()
   where subject_code = p_subject_code and sy = p_sy and period = p_period
     and ( teacher_id = public.current_teacher_id()
        or teacher_id = any (public.sub_owners_of_subject(p_subject_code)) );
end;
$$;
grant execute on function public.teacher_ack_revision_popup(text, text, text) to authenticated;

create or replace function public.teacher_mark_resolved(
  p_subject_code text, p_sy text, p_period text)
returns void language plpgsql security definer set search_path to 'public'
as $$
begin
  update sas_grade_reviews
     set status = 'for_rechecking', popup_seen = true, updated_at = now()
   where subject_code = p_subject_code and sy = p_sy and period = p_period
     and status = 'needs_revision'
     and ( teacher_id = public.current_teacher_id()
        or teacher_id = any (public.sub_owners_of_subject(p_subject_code)) );
  if not found then
    raise exception 'No pending revision for this subject/term';
  end if;
end;
$$;
grant execute on function public.teacher_mark_resolved(text, text, text) to authenticated;


